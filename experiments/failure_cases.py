"""Extract the highest-regret LLM decisions for error analysis (plan section 12.4).

    python experiments/failure_cases.py --exp e1 --top 30

Writes docs/failure_analysis_<exp>.md: for each selected decision, the position summary,
the menu with oracle values, the chosen and the best shot, the rationale and (for MA) every
specialist report. The `Category` line is left for a human to fill in with one of:
(a) ignored scratch/foul risk, (b) pot when a safety dominated, (c) over-cautious safety,
(d) misread position, (e) coordinator followed the wrong specialist, (f) invalid output /
fallback, (g) best shot not in menu (generator limitation), (h) oracle disagreement.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from cuemind.candidates.describe import state_summary
from cuemind.eval.positions import load_positions, menu_at_level

ROOT = Path(__file__).resolve().parents[1]


def main(argv=None) -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--exp", default="e1")
    ap.add_argument("--top", type=int, default=30)
    ap.add_argument("--systems", default="sa,ma")
    a = ap.parse_args(argv)
    dec = [json.loads(x) for x in (ROOT / "results" / a.exp / "decisions.jsonl").read_text(
        encoding="utf-8").splitlines() if x.strip()]
    cfg = json.loads((ROOT / "results" / a.exp / "config_used.json").read_text(encoding="utf-8")) \
        if (ROOT / "results" / a.exp / "config_used.json").exists() else {}
    positions = {}
    for f in (cfg.get("positions") or ["data/positions/test.jsonl", "data/positions/hard_cases.jsonl"]):
        if (ROOT / f).exists():
            positions.update({r["position_id"]: r for r in load_positions(ROOT / f)})
    out = [f"# Failure analysis: {a.exp}", "",
           "Highest-regret decisions per system, generated by `experiments/failure_cases.py`. "
           "Fill in each **Category** line; then summarise counts per system at the top.", ""]
    for system in a.systems.split(","):
        rows = sorted((d for d in dec if d["system_key"] == system and d["position_id"] in positions),
                      key=lambda d: -d["regret"])[: a.top]
        out += [f"## {system} ({len(rows)} decisions)", ""]
        for d in rows:
            rec = positions[d["position_id"]]
            state, menu = menu_at_level(rec, d["access_level"])
            orc = rec["oracle"]
            best = max(orc, key=lambda k: orc[k]["eiv"])
            out += [f"### {d['position_id']} · {d['access_level']} · regret {d['regret']:.2f} "
                    f"({rec['difficulty']}, {', '.join(rec['tags'])})", "",
                    "```", state_summary(state), "```", "",
                    "| id | EIV | shot |", "|---|---|---|"]
            for c in sorted(menu, key=lambda c: -orc[c.shot_id]["eiv"]):
                mark = " **chosen**" if c.shot_id == d["shot_id"] else ""
                mark += " *(best)*" if c.shot_id == best else ""
                out.append(f"| {c.shot_id}{mark} | {orc[c.shot_id]['eiv']:.2f} | {c.description} |")
            out += ["", f"**Rationale:** {d.get('rationale', '')}"]
            for name, rep in ((d.get("trace") or {}).get("reports") or {}).items():
                out.append(f"- *{name}*: top {rep.get('top_choice')}: {rep.get('summary', rep.get('error', ''))}")
            out += ["", "**Category:** _todo_", ""]
    path = ROOT / "docs" / f"failure_analysis_{a.exp}.md"
    path.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
